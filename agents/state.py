"""
agents/state.py
================
Defines the shared state that flows through the LangGraph agent graph.

HOW LANGGRAPH STATE WORKS:
- Every node (agent) in the graph receives the full state as input.
- Each node returns a PARTIAL update to the state.
- LangGraph merges the update into the full state.
- The next node receives the updated state.

This is like a shared whiteboard that all agents can read from and write to.

STATE DESIGN PRINCIPLES:
- All fields are Optional (most are empty at graph start).
- Fields are populated progressively as agents run.
- The final state contains all collected data ready for the report.
"""

from __future__ import annotations

from typing import Annotated, Any, Optional
from typing_extensions import TypedDict

from langchain_core.messages import BaseMessage
from langgraph.graph.message import add_messages


class GraphState(TypedDict):
    """
    The shared state object for the LangGraph execution graph.

    All agents read from and write to this state.
    Fields are populated progressively as agents execute.

    Using TypedDict gives us type safety while working with LangGraph's
    state management system.
    """

    # ----------------------------------------------------------
    # Input fields (set at graph start)
    # ----------------------------------------------------------

    # The original user query
    user_query: str

    # Previous conversation turns — list of {"role": "user"|"assistant", "content": str}.
    # Enables follow-up ("inherited") questions to resolve referents like
    # "what about salaries in India?" right after a role was discussed.
    conversation_history: list[dict]

    # ISO country code filter (e.g., "IN", "US")
    country_filter: Optional[str]

    # All ISO country codes detected in the query (for comparisons)
    countries: list[str]

    # Job role to search for (e.g., "AI Engineer")
    role: Optional[str]

    # True when `role` was never actually mentioned by the user (in this
    # query or an earlier turn) and was filled in by the Planner's generic
    # fallback default instead. Lets downstream agents be honest that a
    # role is a guess-of-last-resort rather than silently presenting it as
    # if the user had asked about that specific role — without this, a
    # user who never mentioned "Software Engineer" would see it quoted
    # back at them as though they had, which reads as the system being
    # hardcoded to one role instead of a dynamic one.
    role_is_default: Optional[bool]

    # Path to uploaded resume file, if any
    resume_path: Optional[str]

    # Technologies to analyze (for trend queries)
    technologies_to_analyze: list[str]

    # ----------------------------------------------------------
    # Classifier output
    # ----------------------------------------------------------

    # Detected intent ("job_market", "tech_trend", "general_chat", ...)
    query_intent: Optional[str]

    # Classifier confidence (0.0 - 1.0)
    intent_confidence: Optional[float]

    # ----------------------------------------------------------
    # Planner output
    # ----------------------------------------------------------

    # The execution plan produced by the Planner agent
    execution_plan: Optional[dict]

    # Detected query type ("job_market", "salary", "tech_trend", etc.)
    query_type: Optional[str]

    # ----------------------------------------------------------
    # MCP call trace (recorded by agents for UI visibility)
    # ----------------------------------------------------------

    # Serialized MCPCallRecord entries — "which agent called which
    # MCP server/tool for which task".
    mcp_calls: list[dict]

    # ----------------------------------------------------------
    # Collected data (populated by collection agents)
    # ----------------------------------------------------------

    # Raw job search results from APIs (serialized JobSearchResult)
    job_search_results: Optional[dict]

    # Skill statistics (serialized list of SkillStatistic dicts)
    skill_statistics: Optional[list[dict]]

    # Salary data (serialized SalaryData)
    salary_data: Optional[dict]

    # GitHub and job-market trend data (serialized TrendSnapshot)
    trend_data: Optional[dict]

    # Country comparison data
    country_comparison: Optional[dict]

    # Parsed resume data (serialized Resume)
    resume_data: Optional[dict]

    # Resume gap analysis (serialized ResumeAnalysis)
    resume_analysis: Optional[dict]

    # ----------------------------------------------------------
    # Agent outputs
    # ----------------------------------------------------------

    # Recommendations generated by the Recommendation agent
    recommendations: list[str]

    # Final report (serialized MarketReport)
    final_report: Optional[dict]

    # Executive summary text (generated by LLM)
    executive_summary: Optional[str]

    # Direct conversational answer (produced by the ChatResponder)
    direct_answer: Optional[str]

    # ----------------------------------------------------------
    # Execution tracking
    # ----------------------------------------------------------

    # All messages (for conversation history display in Chainlit)
    # Annotated with add_messages so LangGraph appends rather than replaces
    messages: Annotated[list[BaseMessage], add_messages]

    # List of agent names that have completed
    completed_agents: list[str]

    # List of errors encountered during execution
    errors: list[str]

    # Whether the graph should stop early due to a critical error
    should_stop: bool

    # Metadata for tracking
    query_id: Optional[str]
    execution_start_time: Optional[str]


def create_initial_state(
    user_query: str,
    country_filter: Optional[str] = None,
    role: Optional[str] = None,
    resume_path: Optional[str] = None,
    technologies: Optional[list[str]] = None,
    query_id: Optional[str] = None,
    conversation_history: Optional[list[dict]] = None,
) -> GraphState:
    """
    Create the initial state for a new graph execution.

    Args:
        user_query: The user's question.
        country_filter: Optional ISO country code.
        role: Optional job role to focus on.
        resume_path: Optional path to an uploaded resume file.
        technologies: Optional list of technologies to analyze.
        query_id: Optional database query ID for tracking.
        conversation_history: Optional previous turns for follow-up context.

    Returns:
        A GraphState dict with all required fields initialized.
    """
    from datetime import datetime

    return GraphState(
        user_query=user_query,
        conversation_history=conversation_history or [],
        country_filter=country_filter,
        countries=[],
        role=role,
        role_is_default=False,
        resume_path=resume_path,
        technologies_to_analyze=technologies or [],
        query_intent=None,
        intent_confidence=None,
        execution_plan=None,
        query_type=None,
        mcp_calls=[],
        job_search_results=None,
        skill_statistics=None,
        salary_data=None,
        trend_data=None,
        country_comparison=None,
        resume_data=None,
        resume_analysis=None,
        recommendations=[],
        final_report=None,
        executive_summary=None,
        direct_answer=None,
        messages=[],
        completed_agents=[],
        errors=[],
        should_stop=False,
        query_id=query_id,
        execution_start_time=datetime.utcnow().isoformat(),
    )
